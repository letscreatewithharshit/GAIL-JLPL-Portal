export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(
    () => localStorage.getItem("gail_portal_language") || "en",
  );
  useEffect(() => {
    localStorage.setItem("gail_portal_language", language);
    document.documentElement.lang = language === "hi" ? "hi" : "en";
  }, [language]);
  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (value) => (language === "hi" ? translations[value] || value : value),
      localize: (record, field) =>
        language === "hi"
          ? record?.[`${field}Hi`] || record?.[field] || ""
          : record?.[field] || "",
    }),
    [language],
  );
  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}
export const useLanguage = () => useContext(LanguageContext);
